// Fictional game scenes and tunable values. No real pay, outcome or risk estimates.
export type DepthChoice = {
  id: string;
  label: string;
  result: string;
  effects: Partial<Record<'health' | 'happiness' | 'knowledge' | 'relationships', number>>;
  cash?: number;
  skill: number;
  safety: number;
  followUp: string;
};

export type DepthEpisode = { id: string; title: string; body: string; choices: DepthChoice[] };
export type SpecialtyDepth = {
  training: DepthEpisode;
  work: DepthEpisode;
  monthly: { employed: number; clinicRevenue: number; clinicCost: number; health: number; happiness: number };
  clinicSetup: number;
};

